"""Builds the short submission logbook from the parts in this folder.

    python3 docs/logbook/submission/build.py          # writes docs/logbook/logbook-submission.md
    python3 docs/logbook/submission/build.py --pdf    # also docs/logbook/logbook-submission.pdf

Edit the part files (0-team.md ... 8-yifei.md), not the output. Figure paths in the parts are relative to
docs/logbook, so the compiled file sits there. The longer per-person sections (<name>.md) and their compiled
logbook.md stay as the full record; this file is the trimmed one to submit and show in the oral.

The PDF uses build_logbook.py's page style and renderer, so it needs the same things: markdown-it-py,
mdit-py-plugins, Google Chrome, and internet access while it runs (MathJax and Mermaid load from jsdelivr).
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LOGBOOK = HERE.parent
OUT = LOGBOOK / "logbook-submission.md"
PDF = LOGBOOK / "logbook-submission.pdf"
TITLE = "AI4R System Project: team logbook"
AUTHORS = ("Ciaran Gruber, Thanh Long Nguyen, Zhenling Zhang, Peiyu Wang, Toby Lee, Yuhao Liu, Chris (Chuhan) Wang, "
           "Yifei Xia")
HEADING = re.compile(r"^(#{2,3})\s+(.*?)\s*$")


def anchor(text: str) -> str:
    """
    :param text: A heading.
    :return: A stable anchor: "Part 3: ..." becomes part-3, "3.2 How it works" becomes s3-2.
    """
    part = re.match(r"Part (\d+)", text)
    if part:
        return f"part-{part.group(1)}"
    number = re.match(r"(\d+)\.(\d+)", text)
    return f"s{number.group(1)}-{number.group(2)}" if number else re.sub(r"\W+", "-", text.lower()).strip("-")


def compile_parts() -> str:
    """:return: The whole logbook as Markdown, with a contents list and an anchor before each heading."""
    body, toc = [], []
    in_fence = False
    for path in sorted(HERE.glob("[0-9]-*.md")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
            heading = None if in_fence else HEADING.match(line)
            if heading:
                level, text = len(heading.group(1)), heading.group(2)
                key = anchor(text)
                body += [f'<a id="{key}"></a>', ""]
                toc.append(f"{'  ' * (level - 2)}- [{text}](#{key})")
            body.append(line)
        body += ["", "---", ""]
    header = [
        "<!-- Generated by docs/logbook/submission/build.py from the part files beside it. Edit those. -->",
        "",
        f"# {TITLE}",
        "",
        AUTHORS,
        "",
        "## Contents",
        "",
        *toc,
        "",
        "---",
        "",
    ]
    return "\n".join(header + body).rstrip() + "\n"


def print_pdf(markdown: str, chrome: str):
    """Prints the compiled logbook to PDF with headless Chrome, in build_logbook.py's page style."""
    sys.path.insert(0, str(LOGBOOK))
    import build_logbook

    with tempfile.TemporaryDirectory() as folder:
        page = Path(folder) / "logbook.html"
        # Shorter figures than the full logbook, so a figure and its explanation share a page
        style = build_logbook.PAGE.replace("max-height: 235mm", "max-height: 105mm")
        page.write_text(style.format(title=TITLE, body=build_logbook.to_html(markdown)), encoding="utf-8")
        subprocess.run([chrome, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                        "--allow-file-access-from-files", "--virtual-time-budget=60000",
                        f"--print-to-pdf={PDF}", page.as_uri()], check=True, capture_output=True, timeout=300)
    print("wrote", PDF, f"({PDF.stat().st_size / 1e6:.1f} MB)")


def main():
    arguments = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    arguments.add_argument("--pdf", action="store_true", help="also print logbook-submission.pdf")
    arguments.add_argument("--chrome", default="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
    options = arguments.parse_args()
    markdown = compile_parts()
    OUT.write_text(markdown, encoding="utf-8")
    print("wrote", OUT, f"({markdown.count(chr(10))} lines)")
    if options.pdf:
        print_pdf(markdown, options.chrome)


if __name__ == "__main__":
    main()
